"""reel.py: storyboard -> reel, for the data-driven reel templates.

  python pipeline/reel.py init   <slug>   storyboard.json -> 03_cues/cues.md, 04_scene/storyboard.js, index.html wiring
  python pipeline/reel.py voice  <slug>   ElevenLabs take (anim.py speak) -> Whisper transcript -> cues
  python pipeline/reel.py check  <slug>   every cue phrase and beat word found in the real transcript? (report)
  python pipeline/reel.py stills <slug>   stills for review
  python pipeline/reel.py render <slug>   the MP4 (after Tony approves the preview)
  python pipeline/reel.py all    <slug>   init -> voice -> check -> stills (stops before render: approval gate)

A project's storyboard lives at videos/<slug>/storyboard.json:
  { "template": "flywheel", "headline": [a, highlight, line2], "keyword": "BUILD", "cta": [line1, line2],
    "ctaPhrase": "exact words", "ctaSub": "...", "ctaNote": "...", "label": "...", "loop": false, "loopPhrase": "...",
    "nodes": [{ "phrase": "exact words starting this beat", "pill": [...], "title": "...", "sub": "...", "emoji": "...",
                "tint": "#...", "avatar": false, "panel": { "type": "chat|form|branches|list|checklist|steps|media|answer|kv", ... } }] }
Beat words inside panels ("word" fields) are matched to the transcript after their node's cue, as the scene does.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PY = str(ROOT / ".venv" / "Scripts" / "python.exe")
TEMPLATES = {"flywheel": "_templates/reel-flywheel/flywheel.js"}
norm = lambda s: re.sub(r"[^a-z0-9$%]", "", s.lower())


def vdir(slug: str) -> Path:
    d = ROOT / "videos" / slug
    if not d.exists():
        sys.exit(f"no project videos/{slug} (create it with: anim.py new {slug} --format tall)")
    return d


def load(slug: str) -> dict:
    return json.loads((vdir(slug) / "storyboard.json").read_text(encoding="utf-8"))


def anim(*args: str) -> None:
    subprocess.run([PY, str(ROOT / "anim.py"), *args], cwd=ROOT, check=True)


def cmd_init(slug: str) -> None:
    d, sb = vdir(slug), load(slug)
    lines = ["# Cues (GENERATED by pipeline/reel.py init from storyboard.json; edit the storyboard, not this file)", ""]
    for i, n in enumerate(sb["nodes"]):
        off = f" {n['offset']:+g}" if n.get("offset") else ""
        lines += [f'## n{i} "{n["phrase"]}"{off}', f"{n['title']}: {n['panel']['type'] if n.get('panel') else 'node only'}", ""]
    if sb.get("loop"):
        lines += [f'## loop "{sb["loopPhrase"]}"', "Zoom out over the whole workflow.", ""]
    lines += [f'## cta "{sb["ctaPhrase"]}"', f"Comment {sb['keyword']}.", ""]
    (d / "03_cues" / "cues.md").write_text("\n".join(lines), encoding="utf-8")
    (d / "04_scene" / "storyboard.js").write_text(
        "// GENERATED by pipeline/reel.py init from ../storyboard.json\nwindow.STORYBOARD = " + json.dumps(sb, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    tpl = "../../../" + TEMPLATES[sb.get("template", "flywheel")]
    (d / "04_scene" / "scene.js").write_text(f"// The scene is the shared template ({tpl}), driven by storyboard.js. Nothing to edit here.\n", encoding="utf-8")
    idx = d / "04_scene" / "index.html"
    html = idx.read_text(encoding="utf-8")
    if "storyboard.js" not in html:
        html = html.replace('<script src="scene.js"></script>', f'<script src="storyboard.js"></script>\n<script src="{tpl}"></script>\n<script src="scene.js"></script>')
        idx.write_text(html, encoding="utf-8")
    print(f"init {slug}: {len(sb['nodes'])} nodes -> cues.md, storyboard.js, index.html")


def find_after(words: list, start: float, key: str) -> float | None:
    k = norm(key)
    for w in words:
        if w["start"] >= start - 0.05 and norm(w["text"]).startswith(k):
            return w["start"]
    return None


def beat_words(p: dict) -> list:
    """The spoken words a panel's beats are keyed to (empty means 'use a timed fallback')."""
    t, w = p.get("type"), []
    pick = lambda rows, i: [r[i] for r in rows if len(r) > i and isinstance(r[i], str) and r[i]]
    if t == "chat": w += [m.get("word") for m in p.get("messages", []) if m.get("word")]
    if t == "form": w += pick(p.get("fields", []), 2)
    if t == "branches": w += pick(p.get("items", []), 2)
    if t == "checklist": w += pick(p.get("items", []), 1)
    if t == "steps": w += pick(p.get("steps", []), 2)
    if t == "media": w += pick(p.get("pills", []), 1)
    if t == "kv": w += pick(p.get("rows", []), 2)
    if t == "list" and p.get("scanWord"): w.append(p["scanWord"])
    if t == "answer" and p.get("result", {}).get("word"): w.append(p["result"]["word"])
    for k in ("button", "bubble", "footer", "pill", "final"):
        if isinstance(p.get(k), dict) and p[k].get("word"): w.append(p[k]["word"])
    return w


def cmd_check(slug: str) -> bool:
    d, sb = vdir(slug), load(slug)
    cj = d / "03_cues" / "cues.json"
    if not cj.exists():
        sys.exit("no cues.json yet: run voice first")
    data = json.loads(cj.read_text(encoding="utf-8"))
    cues, words, ok = data["cues"], data["words"], True
    for i, n in enumerate(sb["nodes"]):
        c = cues.get(f"n{i}")
        if not c:
            print(f"  x n{i}: cue missing"); ok = False; continue
        found = beat_words(n.get("panel") or {})
        missing = [w for w in found if find_after(words, c["start"], w) is None]
        flag = "ok" if not missing else f"MISSING beat words: {missing}"
        print(f"  n{i:<2} {c['start']:6.1f}s  {n['title']:<28} {flag}")
        ok &= not missing
    if find_after(words, cues["cta"]["start"], sb["keyword"]) is None:
        print(f"  x keyword {sb['keyword']} not spoken after the cta cue"); ok = False
    print("check:", "all beats found" if ok else "fix the storyboard words (they must be spoken after their node's cue)")
    return ok


def cmd_voice(slug: str) -> None:
    anim("speak", slug)
    anim("transcribe", slug, "--model", "small", "--force")
    anim("cues", slug)


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    cmd, slug = sys.argv[1], sys.argv[2]
    if cmd == "init": cmd_init(slug)
    elif cmd == "voice": cmd_voice(slug)
    elif cmd == "check": cmd_check(slug)
    elif cmd == "stills": anim("stills", slug, "--hold", "3.5")
    elif cmd == "render": anim("render", slug, "--workers", "1")
    elif cmd == "all":
        cmd_init(slug); cmd_voice(slug); cmd_check(slug); anim("stills", slug, "--hold", "3.5")
        print("Next: preview in the studio, get Tony's approval, then: python pipeline/reel.py render", slug)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
